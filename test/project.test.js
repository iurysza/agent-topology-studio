import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, cp, rm, mkdir, readdir, readFile, writeFile, symlink } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { openProject, StaleError, ProjectPathError } from '../server/project.ts';
test('project listing, refusals and atomic stale-aware writes', async t => {
  const tool = await mkdtemp(path.join(os.tmpdir(), 'studio-project-')); t.after(() => rm(tool, { recursive: true, force: true }));
  const dir = path.join(tool, 'playground'); await cp(new URL('../fixtures/playground', import.meta.url), dir, { recursive: true });
  await mkdir(path.join(tool, 'fixtures/playground'), { recursive: true });
  // Pi shows this message as is, so it carries no CLI flag advice.
  await assert.rejects(openProject(tool, { toolRoot: tool }), { message: "This is the tool's own repo" });
  await assert.rejects(openProject(path.join(tool, 'missing')));
  await assert.rejects(openProject(path.join(tool, 'fixtures/playground'), { toolRoot: tool }), { message: 'fixtures/ is read only' });
  const project = await openProject(dir, { toolRoot: tool });
  const workflows = await project.listWorkflows();
  assert.deepEqual(workflows.map(w => w.id), ['build', 'council', 'plan']);
  assert.ok(workflows.every(w => w.description && w.editable && w.states > 0));
  assert.equal(workflows[0].name, 'Build an approved plan');
  assert.equal((await project.listRoles()).length, 11); assert.ok((await project.listRoles()).every(r => r.description));
  const original = await project.readScript('build'), code = original.code + '\n// changed';
  const sha = await project.writeScript('build', code, original.sha256); assert.equal((await project.readScript('build')).sha256, sha);
  await assert.rejects(project.writeScript('build', 'bad', original.sha256), StaleError); await assert.rejects(project.writeScript('build', 'bad', null), StaleError);
  assert.equal((await project.readScript('build')).code, code);
  await project.writeScript('new', "export const meta = { name: 'Custom', description: 'Hand-written' }; return {};", null);
  assert.deepEqual((await project.listWorkflows()).find(w => w.id === 'new'), { id: 'new', name: 'Custom', description: 'Hand-written', editable: false, states: 0 });
  await project.writeScript('broken', 'not javascript', null);
  assert.equal((await project.listWorkflows()).find(w => w.id === 'broken').editable, false);
  await assert.rejects(project.writeScript('../bad', '', null), /Unsafe/);
  assert.ok(!(await readdir(path.join(dir, '.pi/workflows'))).some(n => n.endsWith('.tmp')));
  assert.equal(await readFile(project.scriptPath('build'), 'utf8'), code);
  assert.equal(await project.deleteScript('new'), true); assert.equal(await project.deleteScript('new'), false);
  assert.deepEqual(await project.readScript('missing'), { code: null, sha256: null });
});
test('concurrent workflow saves allow exactly one writer for the same base hash', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'studio-concurrent-')); t.after(() => rm(root, { recursive: true, force: true }));
  const project = await openProject(root), other = await openProject(root);
  const base = await project.writeScript('demo', 'original', null);
  const results = await Promise.allSettled([project.writeScript('demo', 'first', base), other.writeScript('demo', 'second', base)]);
  assert.equal(results.filter(result => result.status === 'fulfilled').length, 1);
  const rejected = results.find(result => result.status === 'rejected');
  assert.ok(rejected.reason instanceof StaleError);
  const current = await project.readScript('demo'); assert.equal(current.code, 'first');
  assert.equal(rejected.reason.currentSha256, current.sha256);
  await assert.rejects(project.writeScript('demo', 'stale', base), StaleError);
  await project.writeScript('demo', 'after rejection', current.sha256);
  assert.equal((await project.readScript('demo')).code, 'after rejection');
});
test('project rejects workflow and role directory symlinks outside its root', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'studio-symlink-')); t.after(() => rm(root, { recursive: true, force: true }));
  const dir = path.join(root, 'project'), outside = path.join(root, 'project-outside');
  await mkdir(path.join(dir, '.pi'), { recursive: true }); await mkdir(outside);
  await writeFile(path.join(outside, 'demo.js'), 'private workflow');
  await writeFile(path.join(outside, 'coder.md'), 'private role');
  await symlink(outside, path.join(dir, '.pi/workflows')); await symlink(outside, path.join(dir, '.pi/agents'));
  const project = await openProject(dir);
  for (const operation of [() => project.listWorkflows(), () => project.readScript('demo'), () => project.writeScript('demo', 'overwrite', null), () => project.deleteScript('demo'), () => project.listRoles(), () => project.readRole('coder'), () => project.writeRole('coder', {}, 'overwrite', null), () => project.createRole({ name: 'new' })]) await assert.rejects(operation(), ProjectPathError);
  assert.throws(() => project.scriptPath('demo'), ProjectPathError);
  assert.equal(await readFile(path.join(outside, 'demo.js'), 'utf8'), 'private workflow');
  assert.equal(await readFile(path.join(outside, 'coder.md'), 'utf8'), 'private role');
});
test('empty projects and role descriptions need no YAML dependency', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'studio-roles-')); t.after(() => rm(root, { recursive: true, force: true }));
  const project = await openProject(root);
  assert.deepEqual(await project.listWorkflows(), []); assert.deepEqual(await project.listRoles(), []);
  const dir = path.join(root, '.pi/agents'); await mkdir(dir, { recursive: true });
  for (const [name, description] of [['plain', 'Plain description # comment'], ['double', '"Double quoted"'], ['single', "'It''s quoted'"], ['folded', '>\n  First line\n  second line'], ['literal', '|\n  First line\n  second line']]) await writeFile(path.join(dir, `${name}.md`), `---\ndescription: ${description}\nmodel: example\n---\nPrompt`);
  await writeFile(path.join(dir, 'missing.md'), 'No frontmatter');
  assert.deepEqual(Object.fromEntries((await project.listRoles()).map(r => [r.name, r.description])), { plain: 'Plain description', double: 'Double quoted', single: "It's quoted", folded: 'First line second line', literal: 'First line\nsecond line', missing: null });
});
